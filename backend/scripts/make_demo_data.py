"""Generate the synthetic demo dataset backing the web proof of concept.

The output is written to ``data/web/demo/`` and is committed to the repository so
that a fresh clone can run the frontend and backend with no external downloads.

THE OUTPUT IS SYNTHETIC. Sample names, the motif pool and every distribution in
the reference-screen section are measured from the real HPRC callset so the
shapes look right, but the real table is never read here and every locus,
coordinate, allele, verdict and reference repeat below is generated by this
script. It is not a result.

    cd backend && uv run python scripts/make_demo_data.py
"""

